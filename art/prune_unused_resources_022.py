#!/usr/bin/env python3
"""Exclude only independently proven unreachable generated derivatives."""
from pathlib import Path
import copy,hashlib,json,os
from runtime_resource_contract_022 import *

ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'src/main/resources/assets/chao_garden'

def write_json(path,data):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,indent=2)+'\n')

def main():
    from validate_resource_hygiene_022 import selector_contract
    selector_contract(ROOT)
    source=prototype_path(ROOT); payload=source.read_bytes(); original=json.loads(payload)
    assert len(original['bones'])==222
    by_name={b['name']:b for b in original['bones']}
    assert by_name['cocoon']['parent']=='root' and not by_name['root']['meshes']
    shell=by_name['cocoon']['meshes'];assert sum(len(m['vertices']) for m in shell)==208 and sum(len(m['faces']) for m in shell)==220
    archived=ROOT/'art/legacy_runtime/chao_mesh.json';archived.parent.mkdir(parents=True,exist_ok=True);archived.write_bytes(payload)
    minimal={k:copy.deepcopy(v) for k,v in original.items() if k not in ('bones','materials')}
    minimal['materials']={'cocoon':original['materials']['cocoon']}
    minimal['bones']=[copy.deepcopy(by_name[n]) for n in ('root','cocoon')]
    write_json(ASSETS/'models/entity/chao_cocoon.json',minimal)
    candidates=pruning_paths(ROOT)
    # The toy items use block-parent models; the creature uses held_chao.png.
    for p in ASSETS.rglob('*.json'):
        if p.name=='chao_mesh.json':continue
        text=p.read_text()
        for name in UNUSED_ITEM_SPRITES:
            assert f'chao_garden:item/{name}"' not in text, 'An obsolete sprite became referenced: '+str(p)
    report_path=ROOT/'docs/research/RESOURCE_PRUNING_022.json'
    prior=json.loads(report_path.read_text()) if report_path.exists() else {}
    saved={r['path']:r for r in prior.get('removed_resources',[])}
    records=[];removed=0;parents=set()
    for relative in sorted(candidates):
        p=ASSETS/relative
        if p.is_file():
            data=p.read_bytes();record={'path':relative,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}
            p.unlink();parents.add(p.parent);removed+=1
        else:record=saved.get(relative,{'path':relative,'bytes':None,'sha256':None})
        records.append(record)
    if os.name=='posix':
        for parent in parents:
            fd=os.open(parent,os.O_RDONLY|os.O_DIRECTORY)
            try:os.fsync(fd)
            finally:os.close(fd)
    for layout in UNUSED_COAT_LAYOUTS:
        p=ASSETS/'textures/entity/chao/official/coats'/layout
        if p.is_dir() and not any(p.iterdir()):p.rmdir()
    assert not any((ASSETS/p).exists() for p in candidates), 'Deletion postcondition failed'
    manifest_path=ASSETS/'heritage_coats_018.json';manifest=json.loads(manifest_path.read_text())
    manifest['generated_moon_resources']=manifest.get('generated_moon_resources',manifest['moon_resources'])
    manifest['resources']=[p for p in manifest['resources'] if not any(p.startswith(f'textures/entity/chao/official/coats/{layout}/') for layout in UNUSED_COAT_LAYOUTS)]
    manifest['resource_count']=len(manifest['resources']);manifest['moon_resources']=manifest['generated_moon_resources']-4*len(UNUSED_COAT_LAYOUTS)
    assert manifest['resource_count']==755 and manifest['moon_resources']==53
    note='0.22 removes only unreachable generated coat layouts; original reference inputs remain intact.'
    if note not in manifest['notes']:manifest['notes'].append(note)
    write_json(manifest_path,manifest)
    report={'release':'0.22.0','result':'PASS','pruned_asset_count':len(candidates),'removed_on_this_invocation':removed,
      'verified_absent_on_completion':len(candidates),'pruned_bytes':sum(r['bytes'] or 0 for r in records),
      'runtime_coat_layouts':list(COAT_LAYOUTS),'runtime_attachment_layouts':list(ATTACHMENT_LAYOUTS),'runtime_gameplay_forms':list(GAMEPLAY_FORMS),
      'removed_resources':records,'prototype_sha256':hashlib.sha256(payload).hexdigest(),
      'cocoon_sha256':hashlib.sha256((ASSETS/'models/entity/chao_cocoon.json').read_bytes()).hexdigest(),
      'source_bones':222,'runtime_cocoon_bones':2,'directory_fsync_calls':len(parents) if os.name=='posix' else 0}
    write_json(report_path,report)
    print(f'Resource cleanup022: {len(candidates)} unreachable derivatives excluded; {report["pruned_bytes"]} generated bytes; exact cocoon222->2bones.')

if __name__=='__main__':main()
